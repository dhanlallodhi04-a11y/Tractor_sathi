object I18n {
    fun getRateTypeLabel(rateType: String, lang: String = "hi", customUnit: String? = null): String {
        return when (rateType) {
            "HOUR" -> if (lang == "hi") "घंटा" else "hour"
            "ACRE" -> if (lang == "hi") "एकड़" else "acre"
            "BIGHA" -> if (lang == "hi") "बीघा" else "bigha"
            "HECTARE" -> if (lang == "hi") "हेक्टेयर" else "hectare"
            "GUNTHA" -> if (lang == "hi") "गुंठा" else "guntha"
            "KANAL" -> if (lang == "hi") "कनाल" else "kanal"
            "MARLA" -> if (lang == "hi") "मरला" else "marla"
            "CENT" -> if (lang == "hi") "सेंट" else "cent"
            "CHAKKAR" -> if (lang == "hi") "चक्कर" else "trip"
            "DAY" -> if (lang == "hi") "दिन" else "day"
            "FIXED" -> if (lang == "hi") "फिक्स" else "fixed"
            else -> customUnit?.ifEmpty { if (lang == "hi") "यूनिट" else "unit" } ?: (if (lang == "hi") "यूनिट" else "unit")
        }
    }
